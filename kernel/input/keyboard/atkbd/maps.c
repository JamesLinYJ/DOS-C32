input_key_code_t atkbd_internal_set2_keycode(uint16_t code)
{
	if (code < ATKBD_SET2_E0_BASE)
		return set2_base[code];
	if (code < ATKBD_SET2_HIGH_BASE)
		return set2_e0[code - ATKBD_SET2_E0_BASE];
	if (code < ATKBD_SET2_HIGH_END) {
		uint16_t byte = (uint16_t)(code - ATKBD_SET2_HIGH_BASE) |
				0x80u;

		return set2_base[byte];
	}
	return INPUT_KEY_CODE_RESERVED;
}

input_key_code_t atkbd_internal_set1_keycode(uint8_t code, bool extended)
{
	if (code >= ATKBD_SET1_CODE_COUNT)
		return INPUT_KEY_CODE_RESERVED;
	return extended ? set1_e0[code] : set1_base[code];
}
